import { test, expect } from '@playwright/test'

test('PDF frontend requirements: registration, profile, demo administration, sound and typed challenge', async ({ page }, testInfo) => {
  const errors = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.getByRole('button', { name: 'Create an account', exact: true }).click()
  await page.getByLabel('First name', { exact: true }).fill('Sanita')
  await page.getByLabel('Last name', { exact: true }).fill('Savicka')
  await page.getByLabel('Username', { exact: true }).fill('sanitasav')
  await page.getByLabel('Your email', { exact: true }).fill('requirements-' + Date.now() + '@example.com')
  await page.getByLabel('Password', { exact: true }).fill('Strong_123')
  await page.getByLabel('Confirm password', { exact: true }).fill('Different_123')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page.getByRole('alert')).toHaveText('Passwords do not match.')
  await page.getByLabel('Confirm password', { exact: true }).fill('Strong_123')
  await page.getByRole('button', { name: 'Create account', exact: true }).click()
  await expect(page.locator('.alarm-card')).toHaveCount(2)
  await page.getByRole('button', { name: 'Profile & settings', exact: true }).click()
  await expect(page.getByLabel('First name', { exact: true })).toHaveValue('Sanita')
  await page.getByLabel('First name', { exact: true }).fill('Anna')
  await page.getByRole('button', { name: 'Save profile', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('saved in this browser')
  await page.getByRole('button', { name: 'Review account deletion' }).click()
  await expect(page.getByRole('heading', { name: 'Account deletion unavailable' })).toBeVisible()
  await page.getByRole('button', { name: 'Cancel', exact: true }).click()
  await expect(
    page.getByRole('button', { name: 'Admin', exact: true }),
  ).toHaveCount(0)
  for (const width of [320, 390, 1440]) {
    await page.setViewportSize({ width, height: 900 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  }
  await page.getByRole('button', { name: 'Back to alarms', exact: true }).click()
  await page.getByRole('button', { name: 'Profile & settings', exact: true }).click()
  await expect(page.getByLabel('First name', { exact: true })).toHaveValue('Anna')
  await page.getByRole('button', { name: 'Back to alarms', exact: true }).click()
  await page.getByRole('button', { name: '+ add alarm', exact: true }).click()
  await page.getByLabel('Time', { exact: true }).fill('09:35')
  await page.getByLabel('Alarm sound', { exact: true }).selectOption('bell')
  await page.getByLabel('Volume:', { exact: false }).fill('50')
  await page.getByRole('button', { name: 'Save alarm', exact: true }).click()
  await expect(page.locator('.alarm-card')).toHaveCount(3)
  await page.getByRole('button', { name: 'Edit 9:35 AM alarm', exact: true }).click()
  await expect(page.getByLabel('Alarm sound', { exact: true })).toHaveValue('bell')
  await expect(page.getByLabel('Volume:', { exact: false })).toHaveValue('50')
  await page.getByRole('button', { name: 'Close alarm editor' }).click()
  await page.getByRole('button', { name: 'Test alarm', exact: true }).click()
  await page.getByLabel('Character name', { exact: true }).fill('wrong')
  await page.getByRole('button', { name: 'Check answer' }).click()
  await expect(page.getByRole('alert')).toContainText('Incorrect answer')
  await page.reload()
  await expect(page.getByLabel('Character name', { exact: true })).toBeVisible()
  await page.getByLabel('Character name', { exact: true }).fill('  tung   tung tung sahur  ')
  await page.getByRole('button', { name: 'Check answer' }).click()
  await expect(page.getByRole('heading', { name: 'Ready for the day' })).toBeVisible()
  await page.screenshot({ path: testInfo.outputPath('requirements-success.png') })
  expect(errors).toEqual([])
})
